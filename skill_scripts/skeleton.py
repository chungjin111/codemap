def read_text(path, max_bytes=1_500_000):
    try:
        with open(path, "rb") as f:
            data = f.read(max_bytes)
    except OSError:
        return None
    if b"\x00" in data[:4096]:
        return None
    for enc in ("utf-8", "cp949"):
        try:
            return data.decode(enc)
        except UnicodeDecodeError:
            continue
    return data.decode("utf-8", errors="replace")


def _short(s, n):
    s = " ".join(str(s).split())
    return s if len(s) <= n else s[: n - 1] + "…"


def _indent(line):
    return len(line) - len(line.lstrip())


# ── 심볼 추출 ──────────────────────────────────────────────────────────
def py_symbols(text):
    tree = ast.parse(text)
    out = []

    def start_of(node):
        decos = getattr(node, "decorator_list", [])
        return min([node.lineno] + [d.lineno for d in decos])

    def doc(node):
        try:
            d = ast.get_docstring(node, clean=True)
        except Exception:
            d = None
        return _short(d.strip().splitlines()[0], 70) if d and d.strip() else ""

    def decos(node):
        res = []
        for d in getattr(node, "decorator_list", [])[:2]:
            try:
                res.append("@" + _short(ast.unparse(d), 50))
            except Exception:
                pass
        return res

    def fn(node, depth):
        try:
            args = _short(ast.unparse(node.args), 60)
        except Exception:
            args = "…"
        pre = "async def " if isinstance(node, ast.AsyncFunctionDef) else "def "
        return {"kind": "method" if depth else "func", "name": node.name,
                "start": start_of(node), "end": node.end_lineno,
                "sig": "%s%s(%s)" % (pre, node.name, args), "doc": doc(node),
                "depth": depth, "decos": decos(node)}

    entry = False
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            out.append(fn(node, 0))
        elif isinstance(node, ast.ClassDef):
            try:
                bases = ", ".join(ast.unparse(b) for b in node.bases)
            except Exception:
                bases = ""
            out.append({"kind": "class", "name": node.name, "start": start_of(node),
                        "end": node.end_lineno,
                        "sig": "class %s%s" % (node.name, "(%s)" % _short(bases, 40) if bases else ""),
                        "doc": doc(node), "depth": 0, "decos": decos(node)})
            for sub in node.body:
                if isinstance(sub, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    out.append(fn(sub, 1))
        elif isinstance(node, ast.If):
            try:
                if "__name__" in ast.unparse(node.test) and "__main__" in ast.unparse(node.test):
                    entry = True
            except Exception:
                pass
    return out, entry


def _strip_noise(line):
    line = _STR_RE.sub('""', line)
    return re.sub(r"//.*$", "", line)


def brace_end(lines, i, max_look=4000):
    depth, seen = 0, False
    last = min(len(lines), i + max_look)
    for j in range(i, last):
        s = _strip_noise(lines[j])
        for ch in s:
            if ch == "{":
                depth += 1
                seen = True
            elif ch == "}":
                depth -= 1
        if seen and depth <= 0:
            return j
        if not seen:
            if s.rstrip().endswith(";") or j - i >= 5:
                return j if s.rstrip().endswith(";") else i
    return last - 1


def indent_end(lines, i):
    base, last = _indent(lines[i]), i
    for j in range(i + 1, len(lines)):
        if not lines[j].strip():
            continue
        if _indent(lines[j]) <= base:
            if lines[j].strip() == "end":
                return j
            break
        last = j
    return last


def _doc_above(lines, i):
    j = i - 1
    while j >= 0 and lines[j].strip().startswith("@"):
        j -= 1
    if j < 0:
        return ""
    s = lines[j].strip()
    if s.endswith("*/"):
        while j >= 0 and "/*" not in lines[j]:
            j -= 1
        for k in range(max(j, 0), i):
            t = lines[k].strip().lstrip("/*").strip()
            if t and not t.startswith("@"):
                return _short(t.rstrip("*/").strip(), 70)
        return ""
    m = re.match(r"^(?://+|#+|--)\s?(.*)$", s)
    if m:
        while j - 1 >= 0 and re.match(r"^\s*(?://+|#+|--)", lines[j - 1]):
            j -= 1
        m2 = re.match(r"^\s*(?://+|#+|--)\s?(.*)$", lines[j])
        return _short((m2 or m).group(1), 70)
    return ""


def generic_symbols(lines, fam):
    pats = COMPILED.get(fam)
    if not pats:
        return []
    raw = []
    for i, line in enumerate(lines):
        if not line.strip() or len(line) > 400:
            continue
        first = line.split(None, 1)[0] if line.split() else ""
        for kind, rx in pats:
            m = rx.match(line)
            if not m:
                continue
            name = m.group(1)
            if name in CONTROL:
                continue
            if fam == "typed" and kind == "func" and first.rstrip("(") in CONTROL:
                continue  # `return foo(x)` 같은 문장을 함수 정의로 오인하지 않게
            if kind == "type":
                end = brace_end(lines, i) if "{" in line else i
            elif fam in INDENT_FAMILIES:
                end = indent_end(lines, i)
            elif fam in ("sql", "lua", "r", "sh") and "{" not in line:
                end = None
            else:
                end = brace_end(lines, i)
            raw.append({"kind": kind, "name": name, "start": i + 1,
                        "end": (end + 1) if end is not None else None,
                        "sig": _short(line.strip().rstrip("{").rstrip(), 90),
                        "doc": _doc_above(lines, i), "depth": 0, "decos": []})
            break
    for k, s in enumerate(raw):  # 끝을 못 찾은 것은 다음 심볼 직전까지
        if s["end"] is None:
            s["end"] = (raw[k + 1]["start"] - 1) if k + 1 < len(raw) else len(lines)

    out, cls, top_fn_end = [], None, 0
    for s in raw:
        if cls and s["start"] > cls["end"]:
            cls = None
        if s["kind"] == "class":
            if cls is None:
                cls = s
                out.append(s)
            continue
        inside_cls = cls is not None and s["start"] > cls["start"]
        if s["kind"] == "method" and not inside_cls:
            continue
        if inside_cls:
            if s["start"] <= top_fn_end:      # 메서드 안의 중첩 함수
                continue
            s["kind"], s["depth"] = "method", 1
            top_fn_end = s["end"]
            out.append(s)
        else:
            if s["start"] <= top_fn_end:      # 함수 안의 중첩 함수
                continue
            if s["kind"] != "type":
                top_fn_end = s["end"]
            out.append(s)
    return out


# ── import 해석 ────────────────────────────────────────────────────────
def find_imports(text, fam):
    rx = IMPORT_RE.get(fam)
    if not rx:
        return []
    found = []
    for m in rx.finditer(text):
        val = next((g for g in m.groups() if g), None)
        if val and val not in found:
            found.append(val)
    return found[:60]


class Resolver:
    def __init__(self, paths):
        self.noext = {}
        self.by_stem = defaultdict(list)
        for p in paths:
            base = os.path.splitext(p)[0]
            self.noext[base] = p
            stem = os.path.basename(base)
            self.by_stem[stem.lower()].append(p)
            if stem in ("index", "__init__", "mod"):
                self.noext.setdefault(os.path.dirname(base), p)

    def resolve(self, imp, from_path):
        here = os.path.dirname(from_path)
        s = imp.replace("\\", "/").replace("::", "/")
        rel_dots = len(s) - len(s.lstrip(".")) if not s.startswith("./") and not s.startswith("../") else 0
        if s.startswith("./") or s.startswith("../"):
            cand = os.path.normpath(os.path.join(here, s)).replace(os.sep, "/")
            cand = os.path.splitext(cand)[0] if os.path.splitext(cand)[1] in (
                ".js", ".ts", ".jsx", ".tsx", ".mjs", ".dart", ".h", ".hpp", ".rb", ".php") else cand
            return self.noext.get(cand)
        if rel_dots:  # python 상대 import
            base = here
            for _ in range(rel_dots - 1):
                base = os.path.dirname(base)
            cand = os.path.join(base, s.lstrip(".").replace(".", "/")).replace(os.sep, "/")
            return self.noext.get(cand.rstrip("/"))
        s = re.sub(r"^(?:@/|~/|package:[\w\-]+/|crate/|super/|self/)", "", s)
        if "/" not in s and "." in s and not s.endswith((".h", ".hpp", ".dart", ".php", ".rb")):
            s = s.replace(".", "/")
        s = os.path.splitext(s)[0] if "." in os.path.basename(s) else s
        parts = [p for p in s.split("/") if p]
        for n in range(len(parts), 0, -1):          # 긴 꼬리부터 맞춰 본다
            tail = "/".join(parts[-n:])
            hits = [p for b, p in self.noext.items() if b == tail or b.endswith("/" + tail)]
            if not hits and n >= 2:                   # from a.b import name → a/b
                tail2 = "/".join(parts[-n:-1])
                hits = [p for b, p in self.noext.items() if b == tail2 or b.endswith("/" + tail2)]
            if hits:
                hits.sort(key=lambda p: -len(os.path.commonprefix([p, from_path])))
                return hits[0]
            if n == 1:
                cands = self.by_stem.get(parts[-1].lower(), [])
                if len(cands) == 1 and len(parts[-1]) >= 3:
                    return cands[0]
        return None


# ── 파일 하나 분석 ─────────────────────────────────────────────────────
def analyze_file(root, f):
    text = read_text(os.path.join(root, f["path"]))
    if text is None:
        return {"skip": "읽을 수 없음(바이너리)"}
    lines = text.splitlines()
    nonblank = [l for l in lines if l.strip()]
    if not nonblank:
        return {"skip": "빈 파일"}
    if GENERATED_MARKERS.search("\n".join(lines[:6])):
        return {"skip": "자동 생성 표시(헤더)"}
    longest = max(len(l) for l in lines)
    if (len(text) / max(len(lines), 1) > 300) or (longest > 5000 and len(lines) < 50):
        return {"skip": "압축/난독화된 코드로 보임"}

    fam = FAMILY.get(f["lang"])
    entry, syms = False, []
    if fam == "python":
        try:
            syms, entry = py_symbols(text)
        except (SyntaxError, ValueError, RecursionError):
            syms = generic_symbols(lines, "python")
    elif fam:
        syms = generic_symbols(lines, fam)
    markers = [rx for rx in ENTRY_MARKERS if re.search(rx, text, re.M)]
    return {
        "lines": len(lines), "syms": syms, "entry_marker": entry or bool(markers),
        "imports_raw": find_imports(text, fam), "text_lines": lines,
        "hash": hashlib.sha1(text.encode("utf-8", "replace")).hexdigest()[:16],
        "norm_hash": hashlib.sha1(re.sub(r"\s+", "", text).encode("utf-8", "replace")).hexdigest()[:16],
    }


def head_of(root, path, max_chars):
    text = read_text(os.path.join(root, path), 20000) or ""
    if os.path.basename(path).lower() == "package.json":
        try:
            pj = json.loads(text)
            keep = {k: pj[k] for k in ("name", "main", "bin", "scripts") if k in pj}
            deps = list((pj.get("dependencies") or {}).keys())[:25]
            return _short(json.dumps(keep, ensure_ascii=False), max_chars) + \
                ("\n  deps: " + ", ".join(deps) if deps else "")
        except ValueError:
            pass
    text = "\n".join(l.rstrip() for l in text.splitlines() if l.strip())
    return text[:max_chars] + ("…" if len(text) > max_chars else "")


