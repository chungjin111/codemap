def build_skeleton(out_dir, budget=12000):
    with open(os.path.join(out_dir, "manifest.json"), encoding="utf-8") as fp:
        man = json.load(fp)
    root = man["root"]
    code = [f for f in man["files"] if f["role"] == "code"]
    extras = [f for f in man["files"] if f["role"] != "code"]

    infos, skipped = {}, []
    for f in code:
        info = analyze_file(root, f)
        if "skip" in info:
            skipped.append((f["path"], info["skip"]))
            continue
        info["lang"] = f["lang"]
        infos[f["path"]] = info

    # 내용이 완전히 같은 파일은 하나만 본다
    seen_hash, dup_of = {}, {}
    for p in sorted(infos):
        h = infos[p]["norm_hash"]
        if h in seen_hash:
            dup_of[p] = seen_hash[h]
        else:
            seen_hash[h] = p

    # import 그래프
    res = Resolver(list(infos))
    fan_in = Counter()
    for p, info in infos.items():
        local, ext = [], []
        for imp in info["imports_raw"]:
            hit = res.resolve(imp, p)
            if hit and hit != p:
                if hit not in local:
                    local.append(hit)
            elif not imp.startswith("."):
                top = re.split(r"[./:\\]", imp.lstrip("@"))[0]
                if top and top not in ext:
                    ext.append(top)
        info["imports"], info["ext"] = local, ext[:6]
        for hit in local:
            fan_in[hit] += 1

    # 프로젝트 전체 심볼 이름표 → 호출 관계
    defined = defaultdict(set)
    for p, info in infos.items():
        for s in info["syms"]:
            if s["kind"] != "type":
                defined[s["name"]].add(p)
    for p, info in infos.items():
        lines = info["text_lines"]
        covered = [False] * (len(lines) + 2)
        for s in info["syms"]:
            if s["kind"] in ("func", "method"):
                body = "\n".join(lines[s["start"] - 1: s["end"]])
                calls = []
                for name in CALL_RE.findall(body):
                    if name == s["name"] or name in calls or name in COMMON_NAMES:
                        continue
                    where = defined.get(name)
                    if where and (p in where or len(where) <= 3):
                        calls.append(name)
                s["calls"] = calls[:6]
            if s["depth"] == 0:
                for k in range(s["start"], min(s["end"], len(lines)) + 1):
                    covered[k] = True
        top = []
        for k, line in enumerate(lines, 1):
            if covered[k]:
                continue
            for name in CALL_RE.findall(line):
                where = defined.get(name)
                if where and name not in top and name not in COMMON_NAMES:
                    top.append(name)
        info["top_calls"] = top[:8]

    # 중요도
    for p, info in infos.items():
        stem = os.path.splitext(os.path.basename(p))[0]
        toks = set(re.split(r"[_\-.]+", re.sub(r"([a-z])([A-Z])", r"\1_\2", stem).lower()))
        score = 4.0 * fan_in[p] + 1.5 * min(len(info["imports"]), 6) + min(info["lines"], 400) / 40.0
        if info["entry_marker"]:
            score += 30
        if stem.lower() in ENTRY_STEMS:
            score += 10
        if toks & LOW_TOKENS:
            score -= 6
        if stem == "__init__" and info["lines"] < 30:
            score -= 8
        score -= 1.5 * p.count("/")
        if p in dup_of:
            score -= 100
        info["score"] = round(score, 1)
        info["fan_in"] = fan_in[p]
        info["is_entry"] = info["entry_marker"] or (
            stem.lower() in ENTRY_STEMS and fan_in[p] == 0)

    order = sorted(infos, key=lambda p: -infos[p]["score"])

    # 구조가 같은 파일(심볼 구성이 동일)은 첫 파일만 자세히
    shape_first, same_shape = {}, {}
    for p in order:
        shape = tuple((s["kind"], s["name"]) for s in infos[p]["syms"] if s["kind"] != "type")
        if len(shape) >= 3:
            if shape in shape_first:
                same_shape[p] = shape_first[shape]
            else:
                shape_first[shape] = p

    # 이전 실행과 비교 (바뀐 파일만 다시 보면 되도록)
    prev_path = os.path.join(out_dir, "skeleton.json")
    changes = None
    if os.path.exists(prev_path):
        try:
            with open(prev_path, encoding="utf-8") as fp:
                prev = {k: v.get("hash") for k, v in json.load(fp).get("files", {}).items()}
            changes = {
                "changed": sorted(p for p in infos if p in prev and prev[p] != infos[p]["hash"]),
                "added": sorted(p for p in infos if p not in prev),
                "removed": sorted(p for p in prev if p not in infos),
            }
        except (ValueError, OSError):
            changes = None

    # ── 렌더링 (예산 안에서 중요도 순으로 상세도 조절) ──
    def tok(s):
        return int(len(s) / 3.0) + 1

    def render_full(p):
        info = infos[p]
        tags = ["%d줄" % info["lines"]]
        if info["fan_in"]:
            tags.append("←%d" % info["fan_in"])
        if info["is_entry"]:
            tags.append("ENTRY")
        out = ["## %s · %s" % (p, " · ".join(tags))]
        imp = [os.path.splitext(os.path.basename(x))[0] for x in info["imports"]]
        bits = []
        if imp:
            bits.append("imports: " + ", ".join(imp[:10]))
        if info["ext"]:
            bits.append("ext: " + ", ".join(info["ext"]))
        if bits:
            out.append("  " + " | ".join(bits))
        if info["top_calls"]:
            out.append("  (최상위 코드) » " + ", ".join(info["top_calls"]))
        for s in info["syms"]:
            pad = "    " if s["depth"] else "  "
            line = "%s%d-%d %s" % (pad, s["start"], s["end"], s["sig"])
            if s["decos"]:
                line += "  " + " ".join(s["decos"])
            if s.get("calls"):
                line += " » " + ", ".join(s["calls"])
            if s["doc"]:
                line += "  — " + s["doc"]
            out.append(line)
        return "\n".join(out)

    def render_brief(p):
        info = infos[p]
        names = []
        for s in info["syms"]:
            if s["depth"] == 0 and s["kind"] != "type":
                n_m = sum(1 for m in info["syms"] if m["depth"] == 1
                          and s["start"] < m["start"] <= s["end"]) if s["kind"] == "class" else 0
                names.append("%s%s" % (s["name"], "{%d}" % n_m if n_m else ""))
        tag = " ENTRY" if info["is_entry"] else ""
        return "- %s (%d줄, ←%d%s): %s" % (p, info["lines"], info["fan_in"], tag,
                                           _short(", ".join(names), 160) or "(심볼 없음)")

    head = []
    raw_tok = man["totals"]["est_tokens_raw"]
    for f in extras:
        head.append("### %s (앞부분)\n%s" % (f["path"], head_of(root, f["path"], 900 if f["role"] == "readme" else 500)))

    used = sum(tok(h) for h in head)
    full, brief, names_only, levels = [], [], [], {}
    for p in order:
        if p in dup_of:
            names_only.append("%s (= %s 와 내용 동일)" % (p, dup_of[p]))
            levels[p] = 0
            continue
        if p in same_shape:
            brief.append(render_brief(p) + "  ≅ %s 와 같은 구조" % same_shape[p])
            levels[p] = 1
            used += tok(brief[-1])
            continue
        if used < budget * 0.8:
            block = render_full(p)
            if used + tok(block) <= budget * 0.9 or not full:
                full.append(block)
                levels[p] = 2
                used += tok(block)
                continue
        if used < budget:
            brief.append(render_brief(p))
            levels[p] = 1
            used += tok(brief[-1])
        else:
            names_only.append(p)
            levels[p] = 0

    entries = [p for p in order if infos[p]["is_entry"]][:8]
    md = ["# %s — 코드 뼈대" % man["name"],
          "코드 %d개 · 원문 약 %s토큰 → 이 뼈대 약 __TOK__토큰. 표기: `시작-끝줄 시그니처 » 내부 호출  — 설명`, ←n = 이 파일을 import하는 파일 수."
          % (len(infos), format(raw_tok, ","))]
    if raw_tok < 8000:
        md.append("※ 프로젝트가 작다(원문 8천 토큰 미만). 뼈대만 믿지 말고 핵심 파일은 통째로 읽어도 된다.")
    if changes and (changes["changed"] or changes["added"] or changes["removed"]):
        md.append("\n# 지난 분석 이후 달라진 파일 (이것만 다시 보고 analysis.json 의 해당 부분만 고친다)")
        for k, label in (("changed", "수정"), ("added", "추가"), ("removed", "삭제")):
            if changes[k]:
                md.append("- %s: %s" % (label, ", ".join(changes[k][:40])))
    elif changes is not None:
        md.append("\n※ 지난 분석 이후 달라진 파일 없음.")
    if entries:
        md.append("\n# 진입점 후보\n" + "\n".join("- %s" % p for p in entries))
    if head:
        md.append("\n# 프로젝트 명세\n" + "\n".join(head))
    if man["groups"]:
        md.append("\n# 반복 묶음")
        for g in man["groups"]:
            if g["collapsed"]:
                md.append("- %s/%s ×%d — 대표만 분석: %s | 나머지(이름만): %s" % (
                    g["dir"] or ".", g["pattern"], g["count"],
                    ", ".join(os.path.basename(r) for r in g["reps"]),
                    _short(", ".join(g["others"]), 300)))
            else:
                md.append("- %s/%s ×%d — 같은 패턴. 하나만 깊게 읽고 나머지는 같은 구조로 간주해도 된다."
                          % (g["dir"] or ".", g["pattern"], g["count"]))
    md.append("\n# 파일 (중요도 순)")
    md.extend(full)
    if brief:
        md.append("\n# 요약만 (중요도 낮음 · 이름{메서드 수})")
        md.extend(brief)
    if names_only:
        md.append("\n# 이름만 (예산 초과·중복)")
        by_dir = defaultdict(list)
        for p in names_only:
            by_dir[os.path.dirname(p)].append(os.path.basename(p))
        for d in sorted(by_dir):
            md.append("- %s/: %s" % (d or ".", ", ".join(by_dir[d])))
    if skipped:
        md.append("\n# 내용 확인 후 제외 (로컬 판정)")
        md.extend("- %s: %s" % (p, why) for p, why in skipped[:40])
    text = "\n".join(md) + "\n"
    text = text.replace("__TOK__", format(tok(text), ","))

    with open(os.path.join(out_dir, "skeleton.md"), "w", encoding="utf-8") as fp:
        fp.write(text)
    store = {"files": {}}
    for p, info in infos.items():
        store["files"][p] = {
            "hash": info["hash"], "lines": info["lines"], "lang": info["lang"],
            "level": levels.get(p, 0), "score": info["score"],
            "imports": info["imports"], "entry": info["is_entry"],
            "syms": [{k: s[k] for k in ("kind", "name", "start", "end", "depth")} for s in info["syms"]],
        }
    with open(os.path.join(out_dir, "skeleton.json"), "w", encoding="utf-8") as fp:
        json.dump(store, fp, ensure_ascii=False)
    return {
        "files": len(infos), "raw_tokens": raw_tok, "skeleton_tokens": tok(text),
        "full": len(full), "brief": len(brief), "names": len(names_only),
        "skipped": len(skipped), "changes": changes,
        "path": os.path.join(out_dir, "skeleton.md"),
    }


# ── 2단계 · 필요한 줄만 읽기 ───────────────────────────────────────────
def read_ranges(out_dir, specs, budget_lines=1500, max_range=150):
    """`경로:시작-끝` 또는 `경로::심볼이름` 을 받아 줄 번호와 함께 출력한다."""
    with open(os.path.join(out_dir, "manifest.json"), encoding="utf-8") as fp:
        root = json.load(fp)["root"]
    sk = {}
    sk_path = os.path.join(out_dir, "skeleton.json")
    if os.path.exists(sk_path):
        with open(sk_path, encoding="utf-8") as fp:
            sk = json.load(fp)["files"]
    log_path = os.path.join(out_dir, "read_log.json")
    log = {"lines": 0, "ranges": []}
    if os.path.exists(log_path):
        try:
            with open(log_path, encoding="utf-8") as fp:
                log = json.load(fp)
        except ValueError:
            pass

    out, this = [], 0
    for spec in specs:
        if "::" in spec:
            path, sym = spec.split("::", 1)
            hits = [s for s in sk.get(path, {}).get("syms", []) if s["name"] == sym]
            if not hits:
                out.append("!! %s: 심볼 '%s' 을(를) 찾지 못함" % (path, sym))
                continue
            a, b = hits[0]["start"], hits[0]["end"]
        else:
            m = re.match(r"^(.*):(\d+)(?:-(\d+))?$", spec)
            if not m:
                out.append("!! 형식 오류: %s (경로:시작-끝 또는 경로::심볼)" % spec)
                continue
            path, a = m.group(1), int(m.group(2))
            b = int(m.group(3) or a)
        full = os.path.abspath(os.path.join(root, path))
        if not full.startswith(os.path.abspath(root) + os.sep) or not os.path.isfile(full):
            out.append("!! 파일 없음: %s" % path)
            continue
        lines = (read_text(full) or "").splitlines()
        a = max(1, a)
        b = min(len(lines), b)
        cut = b - a + 1 > max_range
        if cut:
            b = a + max_range - 1
        out.append("── %s:%d-%d ──" % (path, a, b))
        out.extend("%d| %s" % (n, lines[n - 1].rstrip()) for n in range(a, b + 1))
        if cut:
            out.append("… (범위가 %d줄을 넘어 잘림. 더 필요하면 이어서 요청)" % max_range)
        this += b - a + 1
        log["ranges"].append("%s:%d-%d" % (path, a, b))
    log["lines"] += this
    with open(log_path, "w", encoding="utf-8") as fp:
        json.dump(log, fp, ensure_ascii=False)
    over = " ⚠ 예산 초과 — 꼭 필요한 것만 더 읽을 것" if log["lines"] > budget_lines else ""
    out.append("[읽기 예산] 이번 %d줄 · 누적 %d/%d줄%s" % (this, log["lines"], budget_lines, over))
    return "\n".join(out)

